export function getClubLogo(name) {
  const key = name.normalize("NFD").replace(/[\u0300-\u036f]/g, "").replace(/ı/g, "i").toLocaleLowerCase("en").replace(/&/g, " and ").replace(/[^a-z0-9]+/g, " ").trim();
  return CLUB_LOGOS[key] || null;
}
